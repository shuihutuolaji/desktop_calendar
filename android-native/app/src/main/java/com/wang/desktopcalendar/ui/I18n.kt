    /** 取当前语言的文案；缺失键回退中文；{k} 占位符用 args 填充 */
    fun t(lang: String, key: String, vararg args: Pair<String, Any?>): String {
        val raw = (STR[lang]?.get(key) ?: STR["zh"]?.get(key)) as? String ?: key
        var s = raw
        for ((k, v) in args) s = s.replace("{$k}", v.toString())
        return s
    }

    /** 列表型文案（星期名等） */
    fun list(lang: String, key: String): List<String> {
        val v = (STR[lang]?.get(key) ?: STR["zh"]?.get(key)) as? List<*>
        return v?.filterIsInstance<String>() ?: emptyList()
    }

    /** 月历表头：中文「周一~周日」，英文 Mon~Sun */
    fun gridWeekday(lang: String, i: Int): String =
        if (lang == "en") list("en", "weekday_names")[i]
        else "周" + list("zh", "weekday_short")[i]

    fun weekdayNames(lang: String): List<String> = list(lang, "weekday_names")

    /** 分钟数转人话时长：45 -> 「45 分钟」，90 -> 「1 小时」，2880 -> 「2 天」 */
    fun humanSpan(lang: String, minutes: Int): String = when {
        minutes < 60 -> t(lang, "span_min", "n" to minutes)
        minutes < 1440 -> t(lang, "span_hour", "n" to minutes / 60)
        else -> t(lang, "span_day", "n" to minutes / 1440)
    }
